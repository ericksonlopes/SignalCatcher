"""Contracts for storage; availability is independent from processing status."""

from collections.abc import Callable
from enum import Enum
from pathlib import Path
from typing import Any, Protocol


class StorageMode(str, Enum):
    LOCAL = "LOCAL"
    DRIVE = "DRIVE"
    BOTH = "BOTH"


class StorageLocation(str, Enum):
    LOCAL = "LOCAL"
    DRIVE = "DRIVE"
    BOTH = "BOTH"
    NONE = "NONE"


class TransferInterrupted(Exception):
    """A paused transfer or lost reservation must not be marked as failed."""


class StorageBlocked(Exception):
    """Authorization, destination permissions or storage quota need attention."""


ProgressCallback = Callable[[int, int, str | None], None]


class IDriveStorage(Protocol):
    def inspect(self) -> dict[str, Any]: ...
    def reserve_id(self) -> str: ...
    def get_file(self, file_id: str) -> dict[str, Any] | None: ...
    def managed_files(self) -> list[dict[str, Any]]: ...
    def upload(
        self,
        path: Path,
        relative_path: str,
        external_id: str,
        file_id: str,
        session_uri: str | None,
        progress: ProgressCallback,
    ) -> dict[str, Any]: ...
    def download(
        self, file_id: str, path: Path, progress: ProgressCallback
    ) -> None: ...
    def save_catalog(self, entries: list[dict[str, Any]]) -> None: ...


class IStorageRepository(Protocol):
    def settings(self) -> dict[str, Any]: ...
    def candidates(self) -> list[dict[str, Any]]: ...
    def observe(
        self, content_id: int, local: str | None, remote: bool | None
    ) -> None: ...
    def reconcile(self, observations: list[dict[str, Any]], mode: str) -> None: ...
    def enqueue(self, content_id: int, operation: str, mode: str) -> None: ...
    def claim(self) -> dict[str, Any] | None: ...
    def checkpoint(
        self, task: dict[str, Any], sent: int, total: int, session_uri: str | None
    ) -> None: ...
    def reserve_remote(self, task: dict[str, Any], file_id: str) -> None: ...
    def finish(self, task: dict[str, Any], result: dict[str, Any]) -> None: ...
    def fail(self, task: dict[str, Any], error: str, blocked: bool = False) -> None: ...
    def release(self, task: dict[str, Any]) -> None: ...
    def record_health(self, info: dict[str, Any], error: str | None = None) -> None: ...
    def catalog(self) -> list[dict[str, Any]]: ...
    def catalog_result(self, error: str | None) -> None: ...
    def staging_removed(self, content_id: int) -> None: ...
    def staging_cleanup_failed(self, content_id: int, error: str) -> None: ...


class IStorageFiles(Protocol):
    root: Path

    def inventory(self) -> dict[str, Path]: ...
    def size(self, path: Path) -> int: ...
    def locate(
        self, item: dict[str, Any], inventory: dict[str, Path]
    ) -> Path | None: ...
    def from_public(self, value: str | None) -> Path | None: ...
    def confined(self, path: Path) -> Path: ...
    def relative(self, path: Path) -> str: ...
    def public(self, path: Path) -> str: ...
    def destination(
        self, item: dict[str, Any], relative: str | None = None
    ) -> Path: ...
    def checksum(self, path: Path) -> str: ...
